defmodule Muro.EmitExamplesTest do
  use ExUnit.Case, async: false

  Code.require_file("emit_examples.exs", __DIR__)

  # A previous test in this process can leave checker state behind.
  # The picture is the one a fresh process emits. The walk is the
  # whole examples tree, so the cap sits above the module default.
  @tag timeout: 180_000
  test "every example that existed before the family emits the same image" do
    got =
      fn -> Muro.EmitExamples.lines() end
      |> Task.async()
      |> Task.await(:infinity)

    expected =
      "test/fixtures/emit-examples.digest"
      |> File.read!()
      |> String.trim_trailing()
      |> String.split("\n")

    assert got == expected
  end

  # `:elixir`, `:otp`, `:node`, and ExUnit `:source` are raw bytes, so a
  # header comment and a line break both move the digest. `:fsm` is the
  # parsed image: the line break is the same image, and the comment text
  # is not. See `test/emit_examples.exs`.
  test "a header comment stays in the image, and only the state machine is parsed" do
    source = """
    defmodule Foo do
      # Generated by Muro. Evidence never becomes a run.
      def bar, do: {:vec, :nat,
        {:var, :k}}
    end
    """

    flat = String.replace(source, "{:vec, :nat,\n    {:var, :k}}", "{:vec, :nat, {:var, :k}}")
    retitled = String.replace(source, "Evidence never becomes a run.", "edited")

    picture = %{
      elixir: {:ok, source},
      otp: {:ok, source},
      node: {:ok, source},
      exunit: %{source: source, skips: [], tests: 0},
      fsm: {:ok, source},
      c: {:ok, "h", "c"}
    }

    hashed = fn pic ->
      pic |> Muro.EmitExamples.canon_picture() |> :erlang.term_to_binary([:deterministic])
    end

    base = hashed.(picture)

    assert hashed.(%{picture | elixir: {:ok, retitled}}) != base
    assert hashed.(%{picture | elixir: {:ok, flat}}) != base
    assert hashed.(%{picture | otp: {:ok, retitled}}) != base
    assert hashed.(%{picture | node: {:ok, retitled}}) != base

    assert hashed.(%{picture | exunit: %{source: retitled, skips: [], tests: 0}}) != base
    assert hashed.(%{picture | exunit: %{source: flat, skips: [], tests: 0}}) != base

    assert hashed.(%{picture | fsm: {:ok, flat}}) == base
    assert hashed.(%{picture | fsm: {:ok, retitled}}) != base
    assert hashed.(%{picture | c: {:ok, "h", "changed"}}) != base
  end
end
